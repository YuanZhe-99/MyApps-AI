/// Purpose: Generate both binding files.
/// Inputs: [args], optionally the libclang path.
/// Returns: None.
/// Side effects: Writes the two generated files.
/// Notes: None.
Future<void> main(List<String> args) async {
  final root = Platform.script.resolve('../');
  final include = root.resolve('third_party/llama.cpp/include/');
  final libclang = args.isNotEmpty ? args.first : _visualStudioLibclang();
  const preamble =
      '// Generated by tool/ffigen.dart from the vendored llama.cpp\n'
      '// headers (third_party/llama.cpp). Do not edit by hand.\n'
      '// ignore_for_file: type=lint';

  Input input(String header) => Input(
    entryPoints: [include.resolve(header)],
    compilerOptions: ['-I${include.toFilePath()}'],
  );

  await FfiGenerator(
    input: input('llama.h'),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/llama_bindings.g.dart')),
      preamble: preamble,
      style: const NativeExternalBindings(
        assetId: 'package:myapps_ai_llm_llama/llama',
      ),
    ),
    visitors: [
      Visitor(
        func: (f) => f.isIncluded = _llamaFunctions.contains(f.name),
        // Passed by pointer, so it would otherwise be opaque; the backend
        // fills its fields.
        struct: (s) {
          if (s.name == 'llama_chat_message') s.isIncluded = true;
        },
      ),
    ],
  ).generate(libclangDylib: libclang == null ? null : Uri.file(libclang));

  await FfiGenerator(
    input: input('ggml-backend.h'),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/ggml_bindings.g.dart')),
      preamble: preamble,
      style: const DynamicLibraryBindings(
        wrapperName: 'GgmlBindings',
        wrapperDocComment:
            'The ggml functions the backend calls, looked up in '
            'whichever loaded library exports them.',
      ),
    ),
    visitors: [
      Visitor(func: (f) => f.isIncluded = _ggmlFunctions.contains(f.name)),
    ],
  ).generate(libclangDylib: libclang == null ? null : Uri.file(libclang));
}

/// Purpose: Find libclang in Visual Studio's LLVM component.
/// Inputs: None.
/// Returns: Its path, or null to let ffigen search its default places.
/// Side effects: Runs `vswhere` on Windows.
/// Notes: The component matches the host: ARM64 on an ARM64 machine.
String? _visualStudioLibclang() {
  if (!Platform.isWindows) return null;
  final vswhere =
      '${Platform.environment['ProgramFiles(x86)']}\\Microsoft Visual Studio\\Installer\\vswhere.exe';
  if (!File(vswhere).existsSync()) return null;
  final result = Process.runSync(vswhere, [
    '-latest',
    '-property',
    'installationPath',
  ]);
  final vs = '${result.stdout}'.trim();
  final arch = Abi.current() == Abi.windowsArm64 ? 'ARM64' : 'x64';
  final dll = '$vs\\VC\\Tools\\Llvm\\$arch\\bin\\libclang.dll';
  return File(dll).existsSync() ? dll : null;
}
