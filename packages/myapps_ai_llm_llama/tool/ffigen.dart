/// Purpose: Regenerate the Dart bindings from the vendored llama.cpp headers.
/// Inputs: Optionally the path to `libclang` as the first argument; otherwise
/// Visual Studio's LLVM component on Windows, then ffigen's default places.
/// Returns: None.
/// Side effects: Rewrites `lib/src/llama_bindings.g.dart` and
/// `lib/src/ggml_bindings.g.dart`.
/// Notes: Run after the headers in `third_party/llama.cpp/include/` change,
/// which happens only when `native/binaries.json` moves to a new upstream
/// tag — the bindings must describe exactly the version the binaries were
/// built from. Run from this package: `dart run tool/ffigen.dart`.
