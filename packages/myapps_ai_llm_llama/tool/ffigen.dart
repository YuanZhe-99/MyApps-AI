/// The ggml entry points: backend loading, the device list and the version.
/// They live in the ggml libraries beside llama's, or inside llama's own
/// binary on Apple, so they are looked up at run time rather than bound to
/// an asset.
const _ggmlFunctions = {
  'ggml_version',
  'ggml_commit',
  'ggml_backend_load',
  'ggml_backend_load_all_from_path',
